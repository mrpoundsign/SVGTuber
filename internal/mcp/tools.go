// ExecuteTool runs the designated SVGTuber tool and returns JSON-RPC content blocks.
func ExecuteTool(name string, args json.RawMessage) (*CallToolResult, error) {
	return HandleToolCall(name, args)
}

// HandleToolCall executes the corresponding SVGTuber tool and returns JSON-RPC content blocks.
func HandleToolCall(name string, args json.RawMessage) (*CallToolResult, error) {
	switch name {
	case "svgtuber_inspect_rig":
		var p struct {
			SVGPath string `json:"svg_path"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_inspect_rig: %w", err)
		}
		report, err := InspectRig(p.SVGPath)
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(report)

	case "svgtuber_auto_rig":
		var p struct {
			SVGPath           string `json:"svg_path"`
			OutputPath        string `json:"output_path"`
			OverwriteExisting bool   `json:"overwrite_existing"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_auto_rig: %w", err)
		}
		res, err := AutoRig(p.SVGPath, p.OutputPath, AutoRigOptions{OverwriteExisting: p.OverwriteExisting})
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(res)

	case "svgtuber_clean_svg":
		var p struct {
			SVGPath    string `json:"svg_path"`
			OutputPath string `json:"output_path"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_clean_svg: %w", err)
		}
		res, err := CleanSVGIDs(p.SVGPath, p.OutputPath)
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(res)

	case "svgtuber_apply_directives":
		var p struct {
			SVGPath    string       `json:"svg_path"`
			Tags       []ElementTag `json:"tags"`
			OutputPath string       `json:"output_path"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_apply_directives: %w", err)
		}
		res, err := ApplyDirectives(p.SVGPath, p.Tags, p.OutputPath)
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(res)

	case "svgtuber_validate_rig", "svgtuber_validate_svg":
		var p struct {
			SVGPath string `json:"svg_path"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_validate_rig: %w", err)
		}
		report, err := ValidateSVGRig(p.SVGPath)
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(report)

	case "svgtuber_generate_studio_widget":
		var p struct {
			SVGPath    string `json:"svg_path"`
			Title      string `json:"title"`
			OutputPath string `json:"output_path"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_generate_studio_widget: %w", err)
		}
		outPath, err := GenerateStudioWidget(p.SVGPath, p.Title, p.OutputPath)
		if err != nil {
			return nil, err
		}
		return &CallToolResult{
			Content: []ContentBlock{
				{
					Type: "text",
					Text: "Studio Widget generated successfully at " + outPath,
				},
			},
		}, nil

	case "svgtuber_plan_rig":
		var p struct {
			Archetype    string   `json:"archetype"`
			Style        string   `json:"style"`
			Components   []string `json:"components"`
			CanvasWidth  float64  `json:"canvas_width"`
			CanvasHeight float64  `json:"canvas_height"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_plan_rig: %w", err)
		}
		bp, err := PlanRig(p.Archetype, p.Style, p.Components, p.CanvasWidth, p.CanvasHeight)
		if err != nil {
			return nil, err
		}
		return toJSONToolResult(bp)

	case "svgtuber_derive_directive":
		var p struct {
			PartType     string            `json:"part_type"`
			CustomParams map[string]string `json:"custom_params"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_derive_directive: %w", err)
		}
		directive, pivot := ResolveDirectiveForPart(p.PartType, p.CustomParams)
		res := map[string]string{
			"part_type": p.PartType,
			"directive": directive,
			"pivot":     pivot,
		}
		return toJSONToolResult(res)

	case "svgtuber_simulate_motion":
		var p struct {
			SVGPath   string  `json:"svg_path"`
			Yaw       float64 `json:"yaw"`
			Pitch     float64 `json:"pitch"`
			Roll      float64 `json:"roll"`
			MouthOpen float64 `json:"mouth_open"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_simulate_motion: %w", err)
		}
		sim := SimulateMotion(MotionSimulationInput{
			Yaw:       p.Yaw,
			Pitch:     p.Pitch,
			Roll:      p.Roll,
			MouthOpen: p.MouthOpen,
		})
		return toJSONToolResult(sim)

	case "svgtuber_control_rig":
		var p struct {
			Expression string `json:"expression"`
			Active     bool   `json:"active"`
			ServerURL  string `json:"server_url"`
		}
		if err := json.Unmarshal(args, &p); err != nil {
			return nil, fmt.Errorf("invalid arguments for svgtuber_control_rig: %w", err)
		}
		res, err := ControlRig(p.ServerURL, p.Expression, p.Active)
		if err != nil {
			return nil, err
		}
		return &CallToolResult{
			Content: []ContentBlock{
				{
					Type: "text",
					Text: res,
				},
			},
		}, nil

	default:
		return nil, fmt.Errorf("unknown tool: %s", name)
	}
}

func toJSONToolResult(val any) (*CallToolResult, error) {
	bytes, err := json.MarshalIndent(val, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("failed to serialize result to JSON: %w", err)
	}
	return &CallToolResult{
		Content: []ContentBlock{
			{
				Type: "text",
				Text: string(bytes),
			},
		},
	}, nil
}
